import argparse,json,time,hashlib,subprocess
parser=argparse.ArgumentParser();parser.add_argument('--all',action='store_true');parser.add_argument('--reference',type=Path,default=Path('animation-source/patient-guoman-voice-reference.wav'));args=parser.parse_args()
import torch,soundfile as sf,numpy as np,imageio_ffmpeg
from qwen_tts import Qwen3TTSModel
torch.set_num_threads(4)
root=Path.cwd();work=root/'work/media';out=root/'public/assets/patient-audio';wav_dir=work/'aged-audio';wav_dir.mkdir(parents=True,exist_ok=True);out.mkdir(parents=True,exist_ok=True)
script=json.loads((work/'script.json').read_text(encoding='utf8'));reference=args.reference.resolve();description=json.loads(reference.with_suffix('.json').read_text(encoding='utf8'));ref_hash=hashlib.sha256(reference.read_bytes()).hexdigest();records=[]
