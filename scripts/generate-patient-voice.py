indices=list(range(len(script))) if args.all else [0,3,17]
def is_current(index):
    cached = progress['completed'].get(str(index), {})
    target = out / f'turn-{index+1:02d}.mp3'
    return cached.get('text') == script[index]['patient'] and target.exists() and cached.get('sha256') == hashlib.sha256(target.read_bytes()).hexdigest()
missing=sorted([i for i in indices if not is_current(i)],key=lambda i:len(script[i]['patient']))
for offset in range(0,len(missing),3):
 batch=missing[offset:offset+3];tick=time.monotonic();torch.manual_seed(2040+offset)
 wavs,sr=model.generate_voice_clone(text=[script[i]['patient'] for i in batch],language='Chinese',voice_clone_prompt=prompt,max_new_tokens=1024)
 for index,samples in zip(batch,wavs):
  name=f'turn-{index+1:02d}';wav=wav_dir/(name+'.wav');mp3=out/(name+'.mp3');samples=np.asarray(samples)
  assert samples.size>sr*.25 and np.isfinite(samples).all() and abs(samples).max()>0.01
  assert samples.size/sr<max(10,len(script[index]['patient'])*.8),'Suspiciously long speech'
  sf.write(wav,samples,sr)
